import { execFileSync } from 'node:child_process';
import { readFile, writeFile, mkdir, copyFile, access } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { signingEnvironment } from './signing.mjs';
const root = path.resolve('.');
const javaHome = process.env.JAVA_HOME || path.join(root,'.local/android-tools/jdk');
const sdk = process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT || path.join(root,'.local/android-tools/sdk');
const env = { ...await signingEnvironment(javaHome),JAVA_HOME: javaHome,ANDROID_HOME: sdk };
const previous = await readFile('.local/android-version.json','utf8').then(JSON.parse).catch(() => ({ versionCode: 0 }));
const versionCode = Math.max(Math.floor(Date.now()/1000)-1704067200,previous.versionCode+1);
const versionName = `0.2.0+${versionCode}`;
await mkdir('.local',{ recursive: true }); await writeFile('.local/android-version.json',JSON.stringify({ versionCode,versionName }));
await writeFile('android/local.properties',`sdk.dir=${sdk.replaceAll('\\','\\\\')}\n`);
const run = (file,args,options = {}) => execFileSync(file,args,{ cwd: root,env,stdio: 'inherit',...options });
run(process.execPath,['node_modules/typescript/bin/tsc','--noEmit']);
run(process.execPath,['node_modules/vite/bin/vite.js','build','--config','vite.mobile.config.ts'],{ env: { ...env,VITE_ANDROID_VERSION: versionName } });
run(process.execPath,['node_modules/@capacitor/cli/bin/capacitor','sync','android']);
run(process.env.UMBRA_GRADLE || path.join(root,'android/gradlew'),['--no-daemon','--max-workers=2',...(process.env.UMBRA_GRADLE_INIT_SCRIPT ? ['-I',process.env.UMBRA_GRADLE_INIT_SCRIPT] : []),':app:assembleRelease',`-PumbraVersionCode=${versionCode}`,`-PumbraVersionName=${versionName}`].filter(Boolean),{ cwd: path.join(root,'android') });
const apk = 'android/app/build/outputs/apk/release/app-release.apk';await access(apk);
const verifier = path.join(sdk,'build-tools/36.0.0/apksigner');run(verifier,['verify','--verbose',apk]);
await mkdir('release/android',{ recursive: true }); await copyFile(apk,'release/android/Umbra-android.apk');
const sha256 = createHash('sha256').update(await readFile(apk)).digest('hex');
const commit = execFileSync('git',['rev-parse','HEAD'],{ encoding: 'utf8' }).trim();
const manifest = { schemaVersion: 1,applicationId: 'io.cinessd.android',versionCode,versionName,url: 'https://github.com/AugustodoBRT/Umbra/releases/download/android-latest/Umbra-android.apk',sha256,minSdk: 28,commit,notes: 'Fontes selecionáveis, biblioteca local, player de filmes e audiobooks, downloads e atualização pelo aplicativo.' };
await writeFile('release/android/android-update.json',JSON.stringify(manifest,null,2)+'\n');
await writeFile('release/android/SHA256SUMS.txt',`${sha256}  Umbra-android.apk\n`);
console.log(`APK assinado: release/android/Umbra-android.apk (${versionName}).`);
